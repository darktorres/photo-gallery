"""Generate the embedded upcase table (crates/model/src/upcase_table.rs) from the Unicode Character Database.

The catalog's Windows name key maps each UTF-16 unit through an upcase table, as NTFS's `$UpCase` does
(docs/plans/CATALOG_SIZE_PLAN.md, D1). The table is embedded and versioned, not the running OS's
`RtlUpcaseUnicodeChar` (which varies by Windows build and cannot run on Linux) nor the toolchain's case folding (which
moves with the Rust toolchain's Unicode version), so the keys are the same on every machine.

It is the table NTFS writes: the simple uppercase mapping (UnicodeData.txt field 12) of a BMP code point to another,
kept only when it round-trips (the uppercase's simple lowercase mapping, field 13, is the code point back), from
Unicode 5.1.0. So the final sigma, the dotless i, the long s, the micro sign and the titlecase digraphs keep their own
names (their uppercase lowercases to
another letter), and letters given a case pair after 5.1 (Georgian Mtavruli, Cherokee small letters, Latin Extended-D)
are their own uppercase. Every other unit (supplementary letters' surrogates included) maps to itself. Gate G2 of the
plan checked this against an NTFS volume of Windows 10 (19045), character by character over the whole BMP: the 973
characters it folds, and onto which, are exactly this table's.

Usage: python tools/gen_upcase.py <UnicodeData.txt> <release, 5.1.0>
The input is https://www.unicode.org/Public/<release>/ucd/UnicodeData.txt. The output's header records the release,
the input's SHA-256, and the table's FNV-1a hash, which the catalog's `key_version` mark carries: a changed table
re-keys every catalog.
"""

import hashlib
import sys
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / "crates" / "model" / "src" / "upcase_table.rs"
BMP_END = 0xFFFF
PER_LINE = 6


def pairs(text):
    """The (unit, upper) pairs of the BMP whose simple uppercase mapping is another BMP code point and round-trips (the
    uppercase's simple lowercase mapping is the unit), by unit."""
    upper_of = {}
    lower_of = {}
    for line in text.splitlines():
        fields = line.split(";")
        if len(fields) < 15:
            continue
        code = int(fields[0], 16)
        if fields[12]:
            upper_of[code] = int(fields[12], 16)
        if fields[13]:
            lower_of[code] = int(fields[13], 16)
    out = [
        (unit, upper)
        for unit, upper in upper_of.items()
        if unit <= BMP_END and upper <= BMP_END and unit != upper and lower_of.get(upper) == unit
    ]
    out.sort()
    return out


def fnv1a64(table):
    """FNV-1a, 64-bit, over each pair's two units as little-endian u16s: the table's identity."""
    h = 0xCBF29CE484222325
    for unit, upper in table:
        for byte in unit.to_bytes(2, "little") + upper.to_bytes(2, "little"):
            h ^= byte
            h = (h * 0x100000001B3) & 0xFFFFFFFFFFFFFFFF
    return h


def render(table, release, digest):
    """The Rust source of the table."""
    lines = [
        "//! The upcase table of the Windows name key (`crate::upcase`). Generated by `tools/gen_upcase.py` from the",
        f"//! Unicode Character Database {release} (`UnicodeData.txt`, SHA-256 {digest[:16]}...): the simple uppercase",
        "//! mapping of every BMP code point whose mapping is in the BMP and lowercases back to it, as NTFS writes",
        "//! `$UpCase`. Do not edit; run the generator.",
        "",
        "/// The Unicode release the table was made from.",
        f'pub(crate) const UCD_RELEASE: &str = "{release}";',
        "",
        "/// FNV-1a (64-bit) over the pairs, each unit little-endian: the table's identity, in the `key_version` mark.",
        f"pub(crate) const TABLE_HASH: u64 = 0x{fnv1a64(table):016X};",
        "",
        "/// (unit, its uppercase), by unit. A unit not listed is its own uppercase.",
        "#[rustfmt::skip]",
        f"pub(crate) static PAIRS: [(u16, u16); {len(table)}] = [",
    ]
    for i in range(0, len(table), PER_LINE):
        chunk = table[i : i + PER_LINE]
        lines.append("    " + " ".join(f"(0x{u:04X}, 0x{v:04X})," for u, v in chunk))
    lines.append("];")
    return "\n".join(lines) + "\n"


def main():
    if len(sys.argv) != 3:
        sys.exit("usage: gen_upcase.py <UnicodeData.txt> <release>")
    source = Path(sys.argv[1])
    data = source.read_bytes()
    table = pairs(data.decode("utf-8"))
    OUT.write_text(render(table, sys.argv[2], hashlib.sha256(data).hexdigest()), encoding="utf-8", newline="\n")
    print(f"{len(table)} pairs -> {OUT}")


if __name__ == "__main__":
    main()
